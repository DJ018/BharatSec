"""One database API for every BharatSec store.

- Local development and tests: one SQLite file per module (unchanged behaviour).
- Production on Vercel: a single Postgres database (Neon) when DATABASE_URL / POSTGRES_URL is set.

Modules keep writing SQLite-style SQL with `?` placeholders. For Postgres, statements are
translated once (cached): placeholders, auto-increment IDs, COLLATE NOCASE, case-insensitive
LIKE, and SQLite-only PRAGMAs. Rows behave the same on both backends: row["col"], row[0], dict(row).
"""
import hashlib
import os
import re
import sqlite3
from contextlib import contextmanager
from functools import lru_cache
from pathlib import Path
from typing import Any, Iterable, Iterator, Sequence

DATABASE_URL = (os.getenv("DATABASE_URL") or os.getenv("POSTGRES_URL") or "").strip()
IS_POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))

if IS_POSTGRES:
    import psycopg

    IntegrityError: tuple[type[BaseException], ...] = (sqlite3.IntegrityError, psycopg.IntegrityError)
else:
    psycopg = None  # type: ignore[assignment]
    IntegrityError = (sqlite3.IntegrityError,)


class Row(dict):
    """A dict that also supports positional access, like sqlite3.Row."""

    __slots__ = ("_values",)

    def __init__(self, names: Sequence[str], values: Sequence[Any]):
        super().__init__(zip(names, values))
        self._values = tuple(values)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


@lru_cache(maxsize=512)
def to_postgres(sql: str) -> str:
    """Translate the SQLite dialect used by BharatSec into Postgres."""
    out = sql.replace("%", "%%")  # literal percent signs must be escaped for psycopg
    out = re.sub(r"\bINTEGER PRIMARY KEY AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", out)
    out = re.sub(r"\bUNIQUE COLLATE NOCASE\b", "UNIQUE", out)          # usernames are stored lower-cased
    out = re.sub(r"(\w+) COLLATE NOCASE", r"lower(\1)", out)            # ORDER BY name COLLATE NOCASE
    out = re.sub(r"\bLIKE\b", "ILIKE", out)                             # SQLite LIKE is case-insensitive
    return out.replace("?", "%s")


class _EmptyCursor:
    rowcount = 0

    def fetchone(self):
        return None

    def fetchall(self):
        return []

    def __iter__(self):
        return iter(())


class _PgConnection:
    """Wraps a psycopg connection with the sqlite3 methods BharatSec uses."""

    def __init__(self, raw):
        self._raw = raw

    def execute(self, sql: str, params: Iterable[Any] = ()):
        if sql.lstrip().upper().startswith("PRAGMA"):
            return _EmptyCursor()  # foreign keys are always on in Postgres; table_info has a helper below
        cursor = self._raw.cursor()
        cursor.execute(to_postgres(sql), tuple(params))
        return cursor

    def executemany(self, sql: str, seq_of_params: Iterable[Iterable[Any]]):
        cursor = self._raw.cursor()
        cursor.executemany(to_postgres(sql), [tuple(p) for p in seq_of_params])
        return cursor

    def executescript(self, script: str) -> None:
        for statement in (part.strip() for part in script.split(";")):
            if statement:
                self.execute(statement)

    def commit(self) -> None:
        self._raw.commit()

    def rollback(self) -> None:
        self._raw.rollback()

    def close(self) -> None:
        self._raw.close()


def _pg_row_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []
    return lambda values: Row(names, values)


def _connect_sqlite(path: Path, timeout: float) -> sqlite3.Connection:
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path, timeout=timeout)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


def connect(sqlite_path: Path, timeout: float = 15):
    """Open a connection: Postgres in production, otherwise the module's SQLite file."""
    if IS_POSTGRES:
        # prepare_threshold=None: Neon's pooled endpoint (PgBouncer) can't keep prepared statements.
        raw = psycopg.connect(DATABASE_URL, autocommit=False, row_factory=_pg_row_factory,
                              prepare_threshold=None, connect_timeout=10)
        return _PgConnection(raw)
    return _connect_sqlite(Path(sqlite_path), timeout)


@contextmanager
def transaction(sqlite_path: Path, timeout: float = 15) -> Iterator[Any]:
    """Connection that commits on success, rolls back on error, and always closes."""
    connection = connect(sqlite_path, timeout)
    try:
        yield connection
        connection.commit()
    except BaseException:
        connection.rollback()
        raise
    finally:
        connection.close()


def table_columns(connection, table: str) -> set[str]:
    if IS_POSTGRES:
        rows = connection.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_name = ?", (table,)
        ).fetchall()
        return {row[0] for row in rows}
    return {row["name"] for row in connection.execute(f"PRAGMA table_info({table})")}


def schema_lock(connection, name: str) -> None:
    """Serialise schema creation when several serverless instances cold-start at once."""
    if IS_POSTGRES:
        key = int(hashlib.sha256(name.encode()).hexdigest()[:15], 16)
        connection.execute("SELECT pg_advisory_xact_lock(?)", (key,))
